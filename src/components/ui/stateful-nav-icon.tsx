export interface StatefulNavIconProps {
  icon: any;
  active?: boolean;
  className?: string;
  size?: number;
}

/**
 * Renderiza ícones da barra lateral no estilo ChatGPT/HIG:
 * sólido (weight="fill") quando ativo e traço fino (weight="regular") quando inativo.
 */
export function StatefulNavIcon({
  icon: RawIcon,
  active = false,
  className = "size-5 shrink-0",
  size,
}: StatefulNavIconProps) {
  if (!RawIcon) {
    return <SquaresFour weight={active ? "fill" : "regular"} size={size} className={className} />;
  }

  const mapped =
    ICON_BRIDGE.get(RawIcon) ||
    NAME_FALLBACK_MAP[RawIcon?.displayName || RawIcon?.name || ""] ||
    null;

  if (mapped) {
    const PhIcon = mapped;
    return <PhIcon weight={active ? "fill" : "regular"} size={size} className={className} />;
  }

  return <RawIcon weight={active ? "fill" : "regular"} size={size} className={className} />;
}
